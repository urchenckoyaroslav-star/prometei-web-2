/** Focused checks for PROMETEI's English-language crypto encyclopedia. */
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const base=(process.env.SITE_URL||"https://prometei-web-2.pages.dev/").replace(/\/?$/,"/");
const root=path.resolve("dist");
const manifest=JSON.parse(fs.readFileSync("crypto-atlas-index.json","utf8"));
const stories=Array.from({length:10},(_,i)=>JSON.parse(fs.readFileSync("crypto-stories-"+String(i+1).padStart(2,"0")+".json","utf8"))).flat();
assert.equal(manifest.assets.length,50,"There must be exactly 50 Coinbase snapshot assets");
assert.equal(stories.length,50,"There must be exactly 50 written histories");
assert.equal(new Set(manifest.assets.map(x=>x.slug)).size,50);
assert.equal(new Set(stories.map(x=>x.slug)).size,50);
assert.deepEqual(manifest.assets.map(x=>x.rank),Array.from({length:50},(_,i)=>i+1));
const bySlug=new Map(stories.map(s=>[s.slug,s]));
const sitemap=fs.readFileSync(path.join(root,"sitemap.xml"),"utf8");
const htmlDir=path.join(root,"crypto-atlas");
const atlasIndex=fs.readFileSync(path.join(htmlDir,"index.html"),"utf8");
assert.ok(atlasIndex.includes('<html lang="en">'));
assert.ok(atlasIndex.includes('id="coin-search"'),"search control absent");
assert.ok(atlasIndex.includes('data-kind-filter'),"category filters absent");
assert.ok(atlasIndex.includes("50 original profiles"),"50 profiles banner absent");
assert.ok(atlasIndex.includes('PROI'),"PROI comparison intro missing");
assert.ok(sitemap.includes("<loc>"+base+"crypto-atlas/</loc>"),"Hub absent from sitemap");
const proi=fs.readFileSync(path.join(htmlDir,"proi","index.html"),"utf8");
assert.ok(proi.includes("not a publicly traded cryptocurrency"),"Current internal PROI points versus token warning missing");
assert.ok(proi.includes('id="lp-slider"'),"Lunar slider missing");
assert.ok(proi.includes('id="lp-calendar-days"'),"Interactive lunar calendar missing");
assert.ok(proi.includes('id="lp-issuance"'),"Illustrative lunar issuance calculator missing");
assert.ok(proi.includes('id="lp-fee-burn"'),"Illustrative fee burning model missing");
assert.ok(proi.includes('id="lp-config"'),"Lunar model values and phases missing");
assert.ok(proi.includes("10%, 20%")&&proi.includes("90%, 80%"),"Android Lunar Pulse milestones must be disclosed");
assert.ok(proi.includes("50%")&&proi.includes("Relay Vault"),"Actual 50/50 fee split missing");
assert.ok(proi.includes("no public PROI blockchain coin")||proi.includes("no public PROI blockchain"),"Not-live status must remain prominent");
assert.ok(sitemap.includes("<loc>"+base+"crypto-atlas/proi/</loc>"));
const encode=s=>String(s).replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll(">","&gt;").replaceAll('"',"&quot;").replaceAll("'","&#39;");
let totalSentences=0;
for(const [i,a] of manifest.assets.entries()){
 const history=bySlug.get(a.slug);
 assert.ok(history,"Missing editorial content: "+a.slug);
 assert.equal(history.facts.length,14,"Every coin needs fourteen original historic sentences: "+a.slug);
 assert.ok(history.bridge.length>30,"Every coin requires a custom PROI comparison: "+a.slug);
 assert.ok(history.facts.every(x=>x.length>38&&/[.!?]$/.test(x)),"Incomplete sentences: "+a.slug);
 assert.equal(a.coinbasePage,Math.floor(i/10)+1,"Coinbase ranking source page incorrect for "+a.slug);
 const file=path.join(htmlDir,a.slug,"index.html");
 assert.ok(fs.existsSync(file),"Missing asset page "+a.slug);
 const html=fs.readFileSync(file,"utf8");
 const url=base+"crypto-atlas/"+a.slug+"/";
 assert.ok(html.includes('<html lang="en">'),"Incorrect language "+a.slug);
 assert.ok(html.includes('<link rel="canonical" href="'+url+'">'),"Canonical missing: "+a.slug);
 assert.ok(html.includes('name="description"'),"Description missing: "+a.slug);
 assert.ok(html.includes('application/ld+json'),"Schema missing: "+a.slug);
 assert.ok(html.includes('<h1>'+encode(a.name)+' <span>('+encode(a.symbol)+')</span></h1>'),"Title missing: "+a.slug);
 assert.ok(html.includes('aria-label="'+encode(a.name)+' editorial symbol"'),"Missing custom coin icon: "+a.slug);
 assert.ok(html.includes('20 original sentences'),"Twenty-sentence label missing: "+a.slug);
 assert.ok(html.includes("Prometei Iskra"),"PROI discussion missing: "+a.slug);
 assert.ok(html.includes("not a launched cryptocurrency"),"PROI status must be clear: "+a.slug);
 assert.ok(html.includes("future PROI design"),"Lunar issuance must be hypothetical: "+a.slug);
 assert.ok(html.includes("not a forecast"),"No rankings promised: "+a.slug);
 for(const text of history.facts)assert.ok(html.includes(encode(text)),"Missing fact from "+a.slug+": "+text);
 assert.ok(html.includes(encode(history.bridge)),"Missing custom PROI comparison: "+a.slug);
 assert.ok(sitemap.includes("<loc>"+url+"</loc>"),"Sitemap missing "+url);
 assert.ok(!html.includes('href="https://hyperliquid.xyz')&&!html.includes('href="https://pump.fun/'),"Do not link to high-risk speculation services");
 totalSentences+=20;
}
assert.equal(totalSentences,1000);
assert.ok(fs.readFileSync(path.join(root,"index.html"),"utf8").includes('href="/crypto-atlas/"'),"Main website lacks internal links");
assert.ok(fs.readFileSync("crypto-atlas.css","utf8").includes("prefers-reduced-motion"),"Reduced motion accessibility missing");
assert.ok(fs.readFileSync("crypto-atlas.js","utf8").includes("aria-pressed"),"Interactive controls not accessible");
console.log("CRYPTO ATLAS PASS: 50 unique histories × 20 sentences = "+totalSentences+", 52 crawlable EN pages, PROI disclosures, internal links, source snapshot and sitemap.");
