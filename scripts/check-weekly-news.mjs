/** Verify 50 long-form, independently attributed English news pages and ad placement integrity. */
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const base=(process.env.SITE_URL||"https://prometei-web-2.pages.dev/").replace(/\/?$/,"/");
const dist=path.resolve("dist"), newsroom=path.join(dist,"news");
const issues=Array.from({length:5},(_,i)=>JSON.parse(fs.readFileSync("news-week-"+String(i+1).padStart(2,"0")+".json","utf8"))).flat();
const depths=new Map(Array.from({length:4},(_,i)=>JSON.parse(fs.readFileSync("news-depth-"+String(i+1).padStart(2,"0")+".json","utf8"))).flat().map(x=>[x.slug,x]));
const photos=JSON.parse(fs.readFileSync("news-images.json","utf8"));
const config=JSON.parse(fs.readFileSync("site-ad-config.json","utf8"));
const xml=fs.readFileSync(path.join(dist,"sitemap.xml"),"utf8");
const get=f=>fs.readFileSync(f,"utf8");
const safe=s=>String(s).replaceAll("&","&amp;").replaceAll('"',"&quot;");
const categories=new Set(["World","Technology","Economy","Climate","Science","Culture"]);
assert.equal(issues.length,50,"Exactly fifty English news stories must be published");
assert.equal(depths.size,40,"The forty existing stories must be expanded");
assert.equal(new Set(issues.map(x=>x.slug)).size,50);
assert.equal(new Set(issues.map(x=>x.title)).size,50);
assert.equal(config.adsense.enabled,false,"Publisher ads must remain off until publisher/consent are actually verified");
assert.ok(config.house.contactUrl,"Sponsorship path required");
for(const [key,p] of Object.entries(photos)){
 assert.match(p.image,/^https:\/\/images\.unsplash\.com\/photo-/,"Unverified photo source: "+key);
 assert.match(p.creditUrl,/^https:\/\/unsplash\.com\/photos\//);
 assert.ok(p.credit&&p.alt&&p.license==="Unsplash License"&&p.disclaimer.includes("Illustrative"));
}
const root=get(path.join(newsroom,"index.html"));
assert.ok(root.includes('<html lang="en">'));
assert.ok(root.includes('<link rel="canonical" href="'+base+'news/">'));
assert.ok(root.includes('id="story-search"')&&root.includes('data-category-filter'));
assert.ok(root.includes("50 source-linked articles"));
assert.ok(root.includes("Illustrative photo")&&root.includes("Not a photograph"));
assert.ok(root.includes("play.google.com/store/apps/details?id=com.meshnetwork.app"));
assert.ok(xml.includes("<loc>"+base+"news/</loc>"));
const cardMatches=[...root.matchAll(/<a class="nw-card[^>]*>[\s\S]*?<\/a>/g)];
assert.equal(cardMatches.length,50,"Exactly one complete clickable tile per news story — no empty duplicate links");
for(const m of cardMatches){
 assert.ok(m[0].includes("<h3>")&&m[0].includes("<figure")&&m[0].includes("</figure>"),"Malformed card from nested anchor");
 assert.equal((m[0].match(/<a /g)||[]).length,1,"A nested link can create empty duplicate cards");
}
assert.equal((root.match(/data-ad-placement="newsFeed"/g)||[]).length,6,"In-feed sponsor placements expected after every eight stories");
assert.ok(root.includes("ADVERTISEMENT")&&root.includes("House promotion"));
let minWords=Infinity;
for(const story of issues){
 assert.match(story.slug,/^[a-z0-9]+(?:-[a-z0-9]+)*$/);
 assert.ok(categories.has(story.category));
 assert.match(story.date,/^2026-11-(1[5-9]|2[0-2])$/);
 assert.ok(story.lead.length>60&&story.body.length>=2&&story.body.every(p=>p.length>65),story.slug);
 assert.ok(story.why.length>55&&/^https:\/\//.test(story.source.url));
 const d=depths.get(story.slug);
 if(story.body.length===2)assert.equal(d?.sections?.length,3,"Original story missing three extended reporting sections: "+story.slug);
 const allSourceLinks=[story.source,...(story.sources||[]),...(d?.sources||[])];
 assert.ok(new Set(allSourceLinks.map(s=>s.url)).size>=2,"Several distinct sources are required: "+story.slug);
 const words=[story.lead,...story.body,story.why,...(d?.sections||[]).map(x=>x.paragraph)].join(" ").trim().split(/\s+/).length;
 minWords=Math.min(minWords,words);
 assert.ok(words>=155,"Story insufficiently expanded: "+story.slug+" "+words);
 const photo=photos[story.photo];
 assert.ok(photo,"Missing photo: "+story.slug);
 const file=path.join(newsroom,story.slug,"index.html");
 assert.ok(fs.existsSync(file));
 const html=get(file),url=base+"news/"+story.slug+"/";
 assert.ok(html.includes('<html lang="en">'));
 assert.ok(html.includes('<link rel="canonical" href="'+url+'">'));
 assert.ok(html.includes('application/ld+json')&&html.includes('"@type":"NewsArticle"'));
 assert.ok(html.includes('<meta name="description"'));
 assert.ok(html.includes('datetime="'+story.date+'"'));
 assert.ok(html.includes(safe(photo.image)));
 assert.ok(html.includes(photo.credit)&&html.includes(photo.creditUrl));
 assert.ok(html.includes("Not a photograph of this reported event"));
 for(const src of allSourceLinks)assert.ok(html.includes('href="'+safe(src.url)+'"'),"Missing attributed source in "+story.slug+" => "+src.url);
 assert.ok(html.includes('class="nw-source-list"'));
 assert.ok(html.includes('data-ad-placement="newsArticleInline"')&&html.includes('data-ad-placement="newsArticleEnd"'),"Both article ad slots missing: "+story.slug);
 assert.ok(html.includes("ADVERTISEMENT")&&html.includes("House promotion"));
 assert.ok(html.includes('href="'+base+'guides/"')&&html.includes('href="'+base+'crypto-atlas/"'),"Ecosystem links missing: "+story.slug);
 assert.ok(html.includes("play.google.com/store/apps/details?id=com.meshnetwork.app"));
 if(d)for(const sec of d.sections)assert.ok(html.includes(safe(sec.heading))&&html.includes(safe(sec.paragraph)),"Missing deeper research: "+story.slug);
 assert.ok(xml.includes("<loc>"+url+"</loc>"),"Missing sitemap URL "+story.slug);
}
assert.ok(get(path.join(dist,"index.html")).includes("FIFTY STORIES."),"Main homepage teaser outdated");
for(const lang of ["uk","ru","de","es","zh","ja"])assert.ok(get(path.join(dist,lang,"index.html")).includes('href="/news/"'));
assert.ok(get("news.css").includes("prefers-reduced-motion"));
assert.ok(get("news.js").includes("aria-pressed"));
assert.ok(fs.existsSync(path.join(dist,"crypto-atlas","bitcoin","index.html")));
assert.ok(fs.existsSync(path.join(dist,"ru","guides","index.html")));
assert.ok(get(path.join(dist,"crypto-atlas","index.html")).includes('data-ad-placement="cryptoFeed"'));
assert.ok(get(path.join(dist,"crypto-atlas","bitcoin","index.html")).includes('data-ad-placement="cryptoArticleInline"'));
assert.ok(get(path.join(dist,"crypto-atlas","bitcoin","index.html")).includes('data-ad-placement="cryptoArticleEnd"'));
console.log("WEEKLY NEWS PASS: 50 original long-form articles (shortest "+minWords+" words), 51 canonical pages, 2+ source links each, licensed photos, no nested-card links, six feed sponsor slots, two story sponsor slots, crypto slots, and all other atlases.");
